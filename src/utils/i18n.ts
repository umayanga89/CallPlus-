export const formatDuration = (seconds: number, lang: Language = 'en'): string => {
  if (seconds === 0) return lang === 'si' ? 'මගහැරුණි (0 තත්)' : 'Missed (0s)';
  const mins = Math.floor(seconds / 60);
  const secs = seconds % 60;
  if (mins === 0) return `${secs}s`;
  const hours = Math.floor(mins / 60);
  const remMins = mins % 60;
  if (hours > 0) {
    return lang === 'si' ? `${hours} පැය ${remMins} මිනි` : `${hours}h ${remMins}m`;
  }
  return lang === 'si' ? `${mins} මිනි ${secs} තත්` : `${mins}m ${secs}s`;
};

export const formatMinutesToHours = (minutes: number, lang: Language = 'en'): string => {
  const hours = Math.floor(minutes / 60);
  const mins = minutes % 60;
  if (hours === 0) return lang === 'si' ? `${mins} මිනි` : `${mins} mins`;
  return lang === 'si' ? `${hours} පැය ${mins} මිනි` : `${hours}h ${mins}m`;
};
